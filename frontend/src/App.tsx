  async function loadAnalysis(datasetId: string) {















    try {















      const [















        edaResponse,















        previewResponse,















        cleaningResponse,















      ] = await Promise.all([















        fetch(















          `${API}/api/datasets/${datasetId}/eda`















        ),































        fetch(















          `${API}/api/datasets/${datasetId}/preview?limit=${previewLimit}`















        ),































        fetch(















          `${API}/api/datasets/${datasetId}/cleaning-report`















        ),















      ]);















































      if (















        !edaResponse.ok ||















        !previewResponse.ok ||















        !cleaningResponse.ok















      ) {















        throw new Error(















          "Could not load dataset analysis."















        );















      }















































      const edaData =















        await edaResponse.json();































      const previewData =















        await previewResponse.json();































      const cleaningData =















        await cleaningResponse.json();















































      setCharts(















        edaData.charts || []















      );































      setPreview(















        previewData.rows || []















      );































      setCleaning(















        cleaningData















      );































    } catch (error) {















      setError(















        error instanceof Error















          ? error.message















          : "Could not load dataset analysis."















      );















    }















  }















































  // ============================================================

  async function loadPreview(datasetId: string, limit: number) {
    try {
      const response = await fetch(
        `${API}/api/datasets/${datasetId}/preview?limit=${limit}`
      );
      if (!response.ok) return;
      const data = await response.json();
      setPreview(data.rows || []);
    } catch {
      // Keep the current preview if a refresh fails.
    }
  }

  async function loadFullData(
    datasetId: string,
    pageNumber: number,
    pageSize: number
  ) {
    setFullDataLoading(true);
    try {
      const offset = (pageNumber - 1) * pageSize;
      const response = await fetch(
        `${API}/api/datasets/${datasetId}/data?limit=${pageSize}&offset=${offset}`
      );
      if (!response.ok) {
        throw new Error("Could not load the cleaned dataset.");
      }
      const result = await response.json();
      setFullData(result.rows || []);
      setFullDataColumns(result.columns || []);
      setFullDataTotal(Number(result.total_rows || 0));
      setFullDataPage(pageNumber);
      setFullDataPageSize(pageSize);
    } catch (error) {
      setError(
        error instanceof Error
          ? error.message
          : "Could not load the cleaned dataset."
      );
    } finally {
      setFullDataLoading(false);
    }
  }

  function openFullData() {
    if (!id) return;
    setDataView(true);
    void loadFullData(id, 1, fullDataPageSize);
  }

  function closeFullData() {
    setDataView(false);
  }
















