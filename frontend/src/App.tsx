function analysisOptionsFor(type: string) {

  if (type === "scatter") return ["Relationship"];

  if (type === "histogram") return ["Distribution"];

  if (type === "heatmap") return ["Correlation"];

  if (type === "line" || type === "area") return ["Trend", "Sum / Total", "Average", "Median"];

  if (type === "pie" || type === "donut") return ["Count / Frequency", "Sum / Total", "Average"];

  return ["Comparison", "Count / Frequency", "Sum / Total", "Average", "Median"];

}



function analysisFor(type: string, aggregation: string) {

  if (type === "scatter") return "Relationship";

  if (type === "histogram") return "Distribution";

  if (type === "heatmap") return "Correlation";

  if (type === "line" || type === "area") {

    return aggregation === "sum" ? "Sum / Total" : aggregation === "median" ? "Median" : aggregation === "count" ? "Trend" : "Average";

  }

  if (aggregation === "count") return "Count / Frequency";

  if (aggregation === "sum") return "Sum / Total";

  if (aggregation === "median") return "Median";

  return type === "pie" || type === "donut" ? "Average" : "Comparison";

}



function buildChartTitle(type: string, x: string, y: string, aggregation: string) {

  if (type === "scatter") return `${x || "X"} vs ${y || "Y"}`;

  if (type === "histogram") return `Distribution of ${x || "selected field"}`;

  if (type === "heatmap") return "Correlation between numeric fields";

  if (aggregation === "count") return `Count by ${x || "category"}`;

  if (type === "funnel") return `${aggregationLabel(aggregation)} by ${x || "stage"}`;

  return `${aggregationLabel(aggregation)} ${y || "values"} by ${x || "category"}`;

}



function buildChartDescription(type: string, x: string, y: string, aggregation: string) {

  if (type === "scatter") return `Relationship between ${x || "X"} and ${y || "Y"}.`;

  if (type === "histogram") return `Distribution of ${x || "the selected numeric field"}.`;

  if (type === "heatmap") return "Pairwise correlation across the dataset's numeric fields.";

  if (aggregation === "count") return `Frequency of records across ${x || "the selected field"}.`;

  return `${aggregationLabel(aggregation)} ${y || "values"} across ${x || "categories"}.`;

}



function aggregationLabel(aggregation: string) {

  if (aggregation === "sum") return "Total";

  if (aggregation === "median") return "Median";

  if (aggregation === "count") return "Count of";

  return "Average";

}



function formatInsightNumber(value: number) {

  if (!Number.isFinite(value)) return "—";

  return new Intl.NumberFormat("en-IN", { maximumFractionDigits: 2 }).format(value);

}



function buildDeterministicInsight(

  type: string,

  x: string,

  y: string,

  aggregation: string,

  data: any[]

) {

  if (!data.length) return "The selected configuration does not currently produce enough data to describe.";



  if (type === "scatter") {

    const pairs = data

      .map((row) => [Number(row.x), Number(row.y)])

      .filter(([a, b]) => Number.isFinite(a) && Number.isFinite(b));

    if (pairs.length < 2) return "There are not enough numeric observations to calculate a relationship.";

    const meanX = pairs.reduce((sum, [a]) => sum + a, 0) / pairs.length;

    const meanY = pairs.reduce((sum, [, b]) => sum + b, 0) / pairs.length;

    const numerator = pairs.reduce((sum, [a, b]) => sum + (a - meanX) * (b - meanY), 0);

    const denominator = Math.sqrt(

      pairs.reduce((sum, [a]) => sum + (a - meanX) ** 2, 0) *

      pairs.reduce((sum, [, b]) => sum + (b - meanY) ** 2, 0)

    );

    const correlation = denominator ? numerator / denominator : 0;

    const strength = Math.abs(correlation) >= 0.7 ? "strong" : Math.abs(correlation) >= 0.4 ? "moderate" : "weak";

    const direction = correlation >= 0 ? "positive" : "negative";

    return `${x || "X"} and ${y || "Y"} show a ${strength} ${direction} relationship (correlation ${correlation.toFixed(2)}).`;

  }



  if (type === "histogram") {

    const peak = data.reduce((best, row) => Number(row.y) > Number(best?.y ?? -Infinity) ? row : best, data[0]);

    return `The highest concentration is around ${formatInsightNumber(Number(peak.x))}, with ${formatInsightNumber(Number(peak.y))} observations in that bin.`;

  }



  if (type === "heatmap") {

    const cells = data.filter((row) => Number.isFinite(Number(row.value)) && row.x !== row.y);

    if (!cells.length) return "No pairwise relationships were available to summarize.";

    const strongest = cells.reduce((best, row) => Math.abs(Number(row.value)) > Math.abs(Number(best.value)) ? row : best, cells[0]);

    return `${strongest.x} and ${strongest.y} have the strongest observed correlation at ${Number(strongest.value).toFixed(2)}.`;

  }



  const normalized = data

    .map((row) => ({ label: String(row.x ?? row.name ?? "Unknown"), value: Number(row.y ?? row.value) }))

    .filter((row) => Number.isFinite(row.value));

  if (!normalized.length) return "The selected data does not contain a numeric result to summarize.";



  const highest = normalized.reduce((best, row) => row.value > best.value ? row : best, normalized[0]);

  const lowest = normalized.reduce((best, row) => row.value < best.value ? row : best, normalized[0]);

  if (aggregation === "count") {

    return `${highest.label} has the most records (${formatInsightNumber(highest.value)}), while ${lowest.label} has the fewest (${formatInsightNumber(lowest.value)}).`;

  }

  const metric = `${aggregationLabel(aggregation).toLowerCase()} ${y || "values"}`;

  return `${highest.label} has the highest ${metric} at ${formatInsightNumber(highest.value)}, while ${lowest.label} has the lowest at ${formatInsightNumber(lowest.value)}.`;

}



function Heatmap({ data }: { data: any[] }) {

  const labels = Array.from(new Set(data.flatMap((row) => [String(row.x), String(row.y)])));

  const lookup = new Map(data.map((row) => [`${row.y}|${row.x}`, Number(row.value)]));

  const colorFor = (value: number | undefined) => {

    if (!Number.isFinite(value)) return "rgba(124, 58, 237, 0.04)";

    const intensity = Math.min(1, Math.abs(value as number));

    return value as number >= 0

      ? `rgba(124, 58, 237, ${0.08 + intensity * 0.42})`

      : `rgba(15, 23, 42, ${0.08 + intensity * 0.42})`;

  };

  return (

    <div className="heatmap-grid" style={{ gridTemplateColumns: `140px repeat(${labels.length}, minmax(90px, max-content))`, width: "max-content", minWidth: "100%" }}>

      <div className="heatmap-corner" />

      {labels.map((label) => <div className="heatmap-label" key={`x-${label}`}>{label}</div>)}

      {labels.map((rowLabel) => (

        <React.Fragment key={rowLabel}>

          <div className="heatmap-label">{rowLabel}</div>

          {labels.map((colLabel) => {

            const value = lookup.get(`${rowLabel}|${colLabel}`);

            return <div className="heatmap-cell" key={`${rowLabel}-${colLabel}`} style={{ background: colorFor(value) }}>{Number.isFinite(value) ? value?.toFixed(2) : "—"}</div>;

          })}

        </React.Fragment>

      ))}

    </div>

  );

}


